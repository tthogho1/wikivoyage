"""Retrieval HTTP API over ``wikivoyage_articles`` for the web app (``webapp/``).

    uvicorn article_db.api:app --host 127.0.0.1 --port 8001

Qwen3 and SigLIP2 are loaded once at startup (first run downloads ~1.2 GB + ~4.5 GB).
The API only retrieves; the answer is generated by the web app.

    POST /search  multipart: text?, image? (file), top_k, mode, page_type?, is_part_of?, title?, heading?
    GET  /health  collection, row count, loaded encoders
"""
from __future__ import annotations

import io
import logging
import os
from contextlib import asynccontextmanager
from typing import Optional

from fastapi import FastAPI, File, Form, HTTPException, UploadFile
from fastapi.concurrency import run_in_threadpool
from fastapi.middleware.cors import CORSMiddleware

from .config import ArticlesConfig
from .search import SearchFilters, build_searcher

logger = logging.getLogger("wikivoyage.articles.api")
_REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MAX_IMAGE_BYTES = 20 * 1024 * 1024

_state: dict = {}


def _load_dotenv() -> None:
    try:
        from dotenv import load_dotenv
    except ImportError:
        return
    load_dotenv(os.path.join(_REPO_ROOT, ".env"), override=False)


@asynccontextmanager
async def lifespan(app: FastAPI):
    _load_dotenv()
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(name)s: %(message)s")
    cfg = ArticlesConfig.from_env()
    _state["cfg"] = cfg
    _state["searcher"] = build_searcher(cfg)  # raises if credentials or the collection are missing
    logger.info("ready: collection %s", cfg.collection)
    yield
    _state.clear()


app = FastAPI(title="Wikivoyage article retrieval", version="1.0.0", lifespan=lifespan)
_origins = [o.strip() for o in os.environ.get("RETRIEVAL_CORS_ORIGINS", "http://localhost:3000").split(",")
            if o.strip()]
app.add_middleware(CORSMiddleware, allow_origins=_origins, allow_methods=["GET", "POST"], allow_headers=["*"])


@app.get("/health")
def health() -> dict:
    searcher = _state.get("searcher")
    if searcher is None:
        raise HTTPException(503, "not ready")
    try:
        rows = searcher.client.get_collection_stats(searcher.collection).get("row_count")
    except Exception as e:  # noqa: BLE001
        raise HTTPException(503, f"Zilliz unavailable: {e}") from e
    return {"status": "ok", "collection": searcher.collection, "rows": rows,
            "encoders": {"text": searcher.text_embedder is not None, "image": searcher.image_embedder is not None}}


@app.post("/search")
async def search(
    text: Optional[str] = Form(None),
    image: Optional[UploadFile] = File(None),
    top_k: int = Form(5),
    mode: str = Form("both"),
    page_type: Optional[str] = Form(None),
    is_part_of: Optional[str] = Form(None),
    title: Optional[str] = Form(None),
    heading: Optional[str] = Form(None),
) -> dict:
    searcher = _state.get("searcher")
    if searcher is None:
        raise HTTPException(503, "not ready")
    if mode not in ("both", "text", "image"):
        raise HTTPException(422, "mode must be both, text or image")
    if not 1 <= top_k <= 20:
        raise HTTPException(422, "top_k must be 1..20")
    if text is not None and len(text) > 2000:
        raise HTTPException(422, "text longer than 2000 characters")

    img = None
    if image is not None and image.filename:
        data = await image.read(MAX_IMAGE_BYTES + 1)
        if len(data) > MAX_IMAGE_BYTES:
            raise HTTPException(413, "image larger than 20 MB")
        try:
            from PIL import Image

            img = Image.open(io.BytesIO(data))
            img.load()
        except Exception as e:  # noqa: BLE001
            raise HTTPException(422, f"could not decode image: {e}") from e

    filters = SearchFilters(page_type or None, is_part_of or None, title or None, heading or None)
    try:
        # Model inference and Zilliz calls block; keep the event loop free.
        res = await run_in_threadpool(searcher.search, text, img, top_k=top_k, filters=filters, mode=mode)
    except ValueError as e:
        raise HTTPException(422, str(e)) from e
    except Exception as e:  # noqa: BLE001
        logger.exception("search failed")
        raise HTTPException(502, f"search failed: {e}") from e
    return res.to_dict()
